#!/usr/bin/env bash
# Builds the React fixtures into self-contained HTML pages (the fixture server
# does not serve .js files, so the bundle is inlined).
# Needs npm. Usage: tests/e2e/src/build.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
work="${TMPDIR:-/tmp}/ua-e2e-build"
mkdir -p "$work"
( cd "$work" && [ -d node_modules/react-select ] || { npm init -y >/dev/null; npm install --silent esbuild react@18.3.1 react-dom@18.3.1 react-select@5.8.0; } )
NODE_PATH="$work/node_modules" "$work/node_modules/.bin/esbuild" "$here/greenhouse-remix.jsx" \
  --bundle --minify --format=iife --jsx=automatic --define:process.env.NODE_ENV='"production"' \
  --resolve-extensions=.jsx,.js --outfile="$work/greenhouse-remix.js" --log-level=warning \
  --alias:react="$work/node_modules/react" --alias:react-dom="$work/node_modules/react-dom" \
  --alias:react-select="$work/node_modules/react-select"
{
  printf '<!doctype html><html><head><meta charset="utf-8"><title>Research Engineer - Anthropic</title>\n'
  printf '<style>body{font-family:sans-serif;max-width:680px;margin:20px auto}.input-wrapper,.select__container{margin:14px 0}.label{display:block;font-weight:600}.input{width:100%%;padding:6px}textarea.input{height:80px}.helper-text--error{color:#c00}</style></head>\n'
  printf '<body><!-- Generated by tests/e2e/src/build.sh from greenhouse-remix.jsx — edit that, not this. -->\n<div id="app"></div>\n<script>\n'
  cat "$work/greenhouse-remix.js"
  printf '\n</script></body></html>\n'
} > "$here/../greenhouse-remix.html"
echo "wrote tests/e2e/greenhouse-remix.html ($(wc -c < "$here/../greenhouse-remix.html") bytes)"

# The Workday mock (from the user's standalone Workday engine tests): React as
# globals, then the mock itself. Real Workday markup: formField containers,
# searchBox/promptOption lists, spinbutton dates, click_filter, parser ghosts.
NODE_PATH="$work/node_modules" "$work/node_modules/.bin/esbuild" "$here/react-globals.js" \
  --bundle --minify --format=iife --define:process.env.NODE_ENV='"production"' \
  --outfile="$work/react-globals.js" --log-level=warning \
  --alias:react="$work/node_modules/react" --alias:react-dom="$work/node_modules/react-dom"
{
  printf '<!doctype html><html><head><meta charset="utf-8"><title>Senior Software Engineer - Workday</title></head>\n'
  printf '<body><!-- Generated by tests/e2e/src/build.sh from mock-workday.js — edit that, not this. -->\n<div id="root"></div>\n<script>\n'
  cat "$work/react-globals.js"
  # Wrapped like real (bundled) Workday code: its top-level consts would otherwise
  # share the page scope with scripts other extensions inject there.
  printf '\n</script>\n<script>(function () {\n'
  cat "$here/mock-workday.js"
  printf '\n})();</script></body></html>\n'
} > "$here/../workday-mock.html"
echo "wrote tests/e2e/workday-mock.html ($(wc -c < "$here/../workday-mock.html") bytes)"
